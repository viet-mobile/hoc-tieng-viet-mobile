def _vn_tone_key(word):
    last_syllable = word.split()[-1]
    nfd = _ud.normalize('NFD', last_syllable)
    for ch in nfd:
        if ch in _VN_TONE_MARK_TO_KEY:
            return _VN_TONE_MARK_TO_KEY[ch]
    return 'ngang'


def _zh_tone_num(pinyin):
    tone1, tone2, tone3, tone4 = 'āēīōūǖĀĒĪŌŪǕ', 'áéíóúǘÁÉÍÓÚǗ', 'ǎěǐǒǔǚǍĚǏǑǓǙ', 'àèìòùǜÀÈÌÒÙǛ'
    for ch in pinyin:
        if ch in tone1: return 1
        if ch in tone2: return 2
        if ch in tone3: return 3
        if ch in tone4: return 4
    return 5  # neutral tone -- none of the 9 requested pairings target this, kept for completeness


