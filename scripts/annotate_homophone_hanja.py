def strip_h(s):
    return re.sub(r"\([^()]*[一-鿿][^()]*\)", "", s)


def main():
    data = json.load(open(PATH, encoding="utf-8"))
    manual = {strip_h(m): m for m in MANUAL}
    # reading of a hanja string, learned from the words whose Korean meaning is exactly its Sino-Korean reading
    cnt = collections.defaultdict(collections.Counter)
    for g in data:
        for w in g["words"]:
            h = (w.get("hanja") or "").split("→")[0]
            first = re.split("[·(]", w["meaning"]["ko"])[0]
            if re.fullmatch("[一-鿿]+", h) and re.fullmatch("[가-힣]+", first) and len(h) == len(first):
                for c, s in zip(h, first):
                    cnt[c][s] += 1
    rd = {c: v.most_common(1)[0][0] for c, v in cnt.items()}
    left = collections.Counter()
    for g in data:
        for w in g["words"]:
            h = (w.get("hanja") or "").split("→")[0]
            reading = "".join(rd.get(c, "?") for c in h)
            parts = []
            for part in w["meaning"]["ko"].split("·"):
                key = strip_h(part).strip()
                if CJK.search(part):
                    parts.append(part)
                elif key in MANUAL_NOTES:
                    parts.append(MANUAL_NOTES[key])
                elif key == reading and re.fullmatch("[一-鿿]+", h):
                    parts.append(key + "(" + h + ")")
                elif key in manual:
                    parts.append(manual[key])
                else:
                    if key not in SKIP:
                        left[key] += 1
                    parts.append(part)
            w.pop("koHanja", None)
            ko = "·".join(parts)
            if ko != w["meaning"]["ko"]:
                w["koHanja"] = ko
    if "--list" in sys.argv:
        print(len(left)); print(" / ".join(sorted(left)))
        return
    with open(PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    print("annotated", sum(1 for g in data for w in g["words"] if "koHanja" in w), "words; parts without hanja:", len(left))


main()
