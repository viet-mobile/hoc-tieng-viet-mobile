# "문법 및 작문 연습" tab data.
#
# Teaches Vietnamese sentence structure by growing one short sentence word by word,
# the same technique used in the original PPTX conversation-training deck
# ("Đây → Đây là → Đây là số → Đây là số điện thoại ..."), but organized as a
# grammar curriculum instead of situational dialogue: starting from the smallest
# possible sentence (subject + verb) and adding one grammatical piece at a time
# (object, place, time, adjective, possessive, frequency adverb, modal/auxiliary
# verb, degree adverb, negation, question, connector), reusing a small closed set
# of common subjects/verbs/adjectives/adverbs throughout so the learner sees the
# same words recombine rather than memorizing new vocabulary each step.
#
# Every Vietnamese phrase is stored as "pairs": a list of [vietnamese_segment,
# korean_gloss] tuples, one per word/phrase unit, IN VIETNAMESE WORD ORDER. The
# renderer lays each pair out as its own column (Vietnamese segment on top in
# the bigger accent-colored font, its Korean gloss centered directly underneath
# in a smaller font) so the two lines line up word-for-word even though Vietnamese
# words are wider than their Korean glosses -- rather than two independently
# flowing lines of text that drift out of alignment.
#
# The two headline contrasts with Korean, called out in GRAMMAR_INTRO and then
# re-illustrated inside the units themselves:
#   1. 서술어 위치: Korean is SOV (predicate last); Vietnamese is SVO (predicate
#      right after the subject).
#   2. 수식어 위치: Korean modifies before the noun (adjective + noun); Vietnamese
#      modifies after the noun (noun + adjective) -- same for possessives.
# A third, subtler point is added so the picture isn't over-simplified: not every
# modifier in Vietnamese trails its head word. Frequency/tense/modal words
# (thường, đã, đang, sẽ, phải, muốn ...) sit BEFORE the verb, same relative
# order as Korean, and degree words like "rất" sit BEFORE the adjective they
# intensify. Only the noun-adjective and noun-possessive relationship flips.
#
# "title"/"desc"/"note" and every Korean gloss ("kr" fields, and each pair's second
# element) are stored as {"ko","zh","en","ja"} dicts so js_json() (see build_app.py)
# serializes them straight into JS objects app_logic.js's T() helper can read directly.
# A step with no standalone Korean-sentence translation keeps "kr" as a plain empty
# string (not a dict) -- T() passes a plain string straight through either way.

